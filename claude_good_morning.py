def fetch_menu_items(section_name, item_prefix, price_prefix):
    """Return [(name, description, price), ...] for a menu section, in
    document order, skipping empty placeholder rows."""
    response = requests.get(
        MENU_URL,
        headers={"User-Agent": "Mozilla/5.0 (compatible; claude-good-morning/1.0)"},
        timeout=15,
    )
    response.raise_for_status()
    soup = BeautifulSoup(response.content, "html.parser")

    date_str = None
    menu_date = None
    time_tag = soup.find("time")
    if time_tag:
        date_str = time_tag.get_text(strip=True)
        iso = time_tag.get("datetime")
        if iso:
            try:
                menu_date = datetime.fromisoformat(iso.replace("Z", "+00:00")).date()
            except ValueError:
                pass

    section = soup.find(attrs={"data-framer-name": section_name})
    if section is None:
        return [], date_str, menu_date

    def matches(tag, prefix):
        return tag.name == "div" and tag.get("data-framer-name", "").startswith(prefix)

    name_divs = section.find_all(lambda tag: matches(tag, item_prefix))
    price_divs = section.find_all(lambda tag: matches(tag, price_prefix))

    items = []
    for name_div, price_div in zip(name_divs, price_divs):
        name_tag = name_div.find("h4")
        desc_tag = name_div.find("p")
        price_tag = price_div.find("h4")

        name = name_tag.get_text(strip=True) if name_tag else ""
        desc = desc_tag.get_text(strip=True) if desc_tag else ""
        price = price_tag.get_text(strip=True) if price_tag else ""

        if not name or not price:
            continue
        items.append((name, desc, price))

    return items, date_str, menu_date


